"""取得画面から必要なときに開く操作説明。"""

import tkinter as tk
from tkinter import ttk
from tkinter.scrolledtext import ScrolledText

HELP = """設定から取得まで

1. 観測所を追加
観測所記号を入力し「追加」を押します。改行・空白・カンマで区切って複数コードを貼り付けできます。重複は除外します。不要な観測所は一覧で選択し「選択を削除」で取り除きます。

2. 取得条件を設定
「水位・流量・雨量」は1項目を選び、開始年月・終了年月と時間値/日値を指定します。
「ダム諸量」は5項目の時間値を一括取得します。開始日・終了日をYYYY-MM-DD形式で指定してください。長期間も自動分割します。

3. 出力フォルダを指定
「参照」で保存先を選ぶか、パスを直接入力します。Excelは常に出力し、Parquetは追加出力です。
水位等は指定フォルダへExcelを保存します。ダムは観測所と期間のサブフォルダを作成し、Excel1冊の年別シート、全期間CSV、品質情報、原データを保存します。
同じフォルダ・同じ条件で実行すると出力を更新します。ダムは保存済み原データから再開できます。

結果の確認
進捗と結果は画面下に表示されます。結果行を選ぶと詳細が表示され、「Excelを開く」「保存フォルダ」で出力を確認できます。失敗した観測所も表示し、詳細に理由を残します。
水位等の「完了」は取得・出力の完了を意味し、欠測状況はExcelのsummaryで確認してください。ダムの「品質注意」は取得できたが欠測等を含む状態、「一部取得」は未取得区間がある状態です。

ダムの品質7種類
有効: 属性が空欄で有効な数値。0も有効です。
欠測: 属性「$」、または値が空欄・数値変換不可。
未受信: 属性「-」。
閉局: 属性「#」。
不明属性: 未対応の属性記号。
行欠落: 配布データにその日時の行がない。
取得失敗: 通信・解析失敗または中止で未取得。
属性を優先し、有効でない値を0埋めしません。原値と属性はExcelにも残します。

中止について
「中止」で取得を停止します。ダムは取得済み分と未取得区間を保存します。水位等は完了済み観測所の出力が残ります。出力中は保存が終わるまで待つ場合があります。

日時について
24時は翌日0時に正規化されます。ダムの年別シートは元日付の年で分類し、12月31日24時も元年のシートに含めます。
"""


def show_help(parent):
    win = tk.Toplevel(parent)
    win.title("水文データ取得の使い方")
    win.geometry("720x660")
    win.minsize(520, 420)
    win.transient(parent)
    text = ScrolledText(win, wrap="word", font=("Yu Gothic UI", 11), padx=18, pady=16,
                        relief="flat", background="#ffffff")
    text.pack(fill="both", expand=True)
    text.insert("1.0", HELP)
    text.configure(state="disabled")
    ttk.Button(win, text="閉じる", command=win.destroy).pack(pady=8)
    return win
